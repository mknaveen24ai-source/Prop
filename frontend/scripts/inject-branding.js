#!/usr/bin/env node
/**
 * inject-branding.js
 *
 * Reads client.config.json from the REPO ROOT and writes a .env file
 * into the frontend/ directory so Vite picks up the brand
 * env vars at build time.
 *
 * Usage (called automatically by prebuild):
 *   node scripts/inject-branding.js
 *
 * Manual usage:
 *   node scripts/inject-branding.js --config ../../client.config.json
 */

const fs   = require('fs')
const path = require('path')

// ── Resolve config path ───────────────────────────────────────────────────────
const args = process.argv.slice(2)
const configFlag = args.indexOf('--config')
const configPath = configFlag !== -1
  ? path.resolve(args[configFlag + 1])
  : path.resolve(__dirname, '../../client.config.json')

if (!fs.existsSync(configPath)) {
  console.warn(`[inject-branding] No client.config.json found at ${configPath}`)
  console.warn('[inject-branding] Using default branding. Create client.config.json for custom branding.')
  process.exit(0)
}

const config = JSON.parse(fs.readFileSync(configPath, 'utf-8'))

// ── Build .env content ────────────────────────────────────────────────────────
// API URL: if domain is set, use https. Otherwise fall back to localhost for dev.
const apiUrl = config.domain
  ? `https://${config.domain}/api`
  : (process.env.VITE_API_URL || 'http://localhost:5000')

const envLines = [
  `# Auto-generated by inject-branding.js — DO NOT EDIT MANUALLY`,
  `# Re-generated on every build from client.config.json`,
  ``,
  `VITE_FIRM_NAME=${config.firm_name || 'PropFirm'}`,
  `VITE_API_URL=${apiUrl}`,
  `VITE_PRIMARY_COLOR=${config.primary_color || '#0066ff'}`,
  `VITE_SECONDARY_COLOR=${config.secondary_color || '#001133'}`,
  `VITE_ACCENT_COLOR=${config.accent_color || '#ffd700'}`,
  `VITE_SUPPORT_EMAIL=${config.support_email || 'support@propfirm.com'}`,
  `VITE_FIRM_SLUG=${config.firm_slug || 'propfirm'}`,
  `VITE_CURRENCY=${config.currency || 'USD'}`,
  `VITE_LANGUAGE=${config.language || 'en'}`,
  `VITE_TIMEZONE_DISPLAY=${config.timezone_display || 'UTC'}`,
]

const envContent = envLines.join('\n') + '\n'
const envOutputPath = path.resolve(__dirname, '../.env')

fs.writeFileSync(envOutputPath, envContent, 'utf-8')
console.log(`[inject-branding] ✅ Wrote branding env to ${envOutputPath}`)
console.log(`[inject-branding]    Firm: ${config.firm_name}`)
console.log(`[inject-branding]    Domain: ${config.domain || 'localhost (dev)'}`)
console.log(`[inject-branding]    Color: ${config.primary_color}`)
